import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFile} from 'node:fs/promises';
import {cloudProgress} from '../src/cloud.js';
const req=(user,method='GET',body)=>new Request('https://pista.test/api/progress',{method,headers:{origin:'https://pista.test',...(user?{'oai-authenticated-user-id':user}:{})},...(body?{body:JSON.stringify(body)}:{})});
test('cloud backups are isolated by authenticated user and use optimistic concurrency',async()=>{const db=new DatabaseSync(':memory:');db.exec(await readFile(new URL('../drizzle/0001_true_shriek.sql',import.meta.url),'utf8'));const adapter={prepare(sql){return {bind(...args){const stmt=db.prepare(sql);return {async run(){return {meta:{changes:stmt.run(...args).changes}};},async first(){return stmt.get(...args);}};}};}};
 assert.equal((await cloudProgress(req(null),adapter)).status,401);
 const snapshot={coins:123,owned:['fusca','gol'],selected:'gol',best:500};
 assert.equal((await cloudProgress(req('alice','PUT',{save:snapshot,revision:0}),adapter)).status,200);
 assert.equal((await cloudProgress(req('alice','PUT',{save:snapshot,revision:0}),adapter)).status,409);
 const a=await (await cloudProgress(req('alice'),adapter)).json();assert.equal(a.save.coins,123);assert.equal(a.save.selected,'gol');assert.equal(a.revision,1);
 const b=await (await cloudProgress(req('bob'),adapter)).json();assert.equal(b.save,null);
 assert.equal((await cloudProgress(req('alice','PUT',{save:{...snapshot,coins:150},revision:1}),adapter)).status,200);
 assert.equal((await cloudProgress(req('alice','PUT',{save:snapshot,revision:1}),adapter)).status,409);
 assert.equal((await (await cloudProgress(req('alice'),adapter)).json()).save.coins,150);db.close();
});
