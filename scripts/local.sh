#!/usr/bin/env bash
# Runs PISTA 84 locally with its own throwaway MongoDB and Redis in Docker.
# The only requirement is Docker with Compose v2.24 or newer. Usage:
#   bash scripts/local.sh up [--port N] [--lan] [--force-env]
#   bash scripts/local.sh down | reset | logs | status | env | check | test | help
set -euo pipefail

cd "$(dirname "$0")/.."

# Git Bash on Windows would otherwise rewrite container paths in docker arguments.
export MSYS_NO_PATHCONV=1

ENV_EXAMPLE=".env.example"
ENV_FILE=".env.docker"
DEFAULT_PORT="4173"

die() { echo "error: $*" >&2; exit 1; }

# The env file also feeds Compose's own variable substitution (ports); never fall back to a developer's real .env.
compose() {
  [ -f "$ENV_FILE" ] || write_env "$DEFAULT_PORT" "127.0.0.1" "no" > /dev/null
  docker compose --env-file "$ENV_FILE" "$@"
}

require_docker() {
  command -v docker >/dev/null 2>&1 || die "Docker is not installed. Install Docker Desktop or Docker Engine."
  docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required."
  docker info >/dev/null 2>&1 || die "The Docker daemon is not running. Start Docker and try again."
}

# Copies .env.example to .env.docker, pointing it at the Compose services. Existing
# files are kept (they may hold your edits) unless --force-env is given.
write_env() {
  local port="$1" bind="$2" force="$3"
  if [ -f "$ENV_FILE" ] && [ "$force" != "yes" ]; then
    echo "Keeping existing $ENV_FILE (use --force-env to regenerate it)."
    return
  fi
  [ -f "$ENV_EXAMPLE" ] || die "$ENV_EXAMPLE is missing."
  local key
  for key in PISTA84_COINS PISTA84_PROGRESS_TOOLS PORT MONGODB_URI MONGODB_DATABASE REDIS_URL API_ORIGIN PUBLIC_ORIGIN; do
    grep -q "^${key}=" "$ENV_EXAMPLE" || die "$ENV_EXAMPLE no longer defines ${key}; update scripts/local.sh."
  done
  {
    echo "# Generated by scripts/local.sh from $ENV_EXAMPLE for the Docker Compose stack."
    echo "# Safe to edit; regenerate with: bash scripts/local.sh env --force-env. Never commit it."
    tr -d '\r' < "$ENV_EXAMPLE" | sed -E \
      -e "s|^PISTA84_COINS=.*|PISTA84_COINS=|" \
      -e "s|^PISTA84_PROGRESS_TOOLS=.*|PISTA84_PROGRESS_TOOLS=true|" \
      -e "s|^PORT=.*|PORT=${port}|" \
      -e "s|^MONGODB_URI=.*|MONGODB_URI=mongodb://mongo:27017|" \
      -e "s|^MONGODB_DATABASE=.*|MONGODB_DATABASE=pista84|" \
      -e "s|^REDIS_URL=.*|REDIS_URL=redis://redis:6379|" \
      -e "s|^API_ORIGIN=.*|API_ORIGIN=|" \
      -e "s|^PUBLIC_ORIGIN=.*|PUBLIC_ORIGIN=|"
    echo
    echo "# Host interface that publishes the game: 127.0.0.1 (this computer only) or 0.0.0.0 (LAN, for a phone)."
    echo "BIND_ADDRESS=${bind}"
  } > "$ENV_FILE"
  echo "Wrote $ENV_FILE (port ${port}, bound to ${bind})."
}

current_port() {
  local port=""
  if [ -f "$ENV_FILE" ]; then
    port="$(sed -n 's/^PORT=\([0-9]*\).*/\1/p' "$ENV_FILE" | head -n 1)"
  fi
  echo "${port:-$DEFAULT_PORT}"
}

usage() {
  cat <<'EOF'
PISTA 84 local stack (game + MongoDB + Redis in Docker, nothing else needed)

  bash scripts/local.sh up [--port N] [--lan] [--force-env]
        Writes .env.docker from .env.example if missing, builds the image,
        starts everything and waits until it is healthy.
        --port N      host port for the game (default 4173)
        --lan         publish on all interfaces so a phone can reach it
        --force-env   regenerate .env.docker
  bash scripts/local.sh down      Stop the stack; saved data is kept.
  bash scripts/local.sh reset     Stop the stack and delete its MongoDB data.
  bash scripts/local.sh logs      Follow the logs.
  bash scripts/local.sh status    Show container status.
  bash scripts/local.sh env       Only write .env.docker (same flags as up).
  bash scripts/local.sh check     Run the live checks against the local services.
  bash scripts/local.sh test      Run the checks plus typecheck and the Node tests.

The services are private to Docker and use disposable data: never put real
credentials in .env.docker.
EOF
}

command_name="${1:-help}"
[ $# -gt 0 ] && shift

port="" bind="127.0.0.1" force="no" flags_given="no"
while [ $# -gt 0 ]; do
  case "$1" in
    --port) [ $# -ge 2 ] || die "--port needs a number."; port="$2"; flags_given="yes"; shift 2 ;;
    --lan) bind="0.0.0.0"; flags_given="yes"; shift ;;
    --force-env) force="yes"; shift ;;
    *) die "Unknown option: $1 (see: bash scripts/local.sh help)" ;;
  esac
done
case "$port" in
  "") ;;
  *[!0-9]*) die "--port must be a number." ;;
  *) { [ "$port" -ge 1 ] && [ "$port" -le 65535 ]; } || die "--port must be between 1 and 65535." ;;
esac
[ "$flags_given" = "yes" ] && force="yes"

case "$command_name" in
  help|-h|--help)
    usage
    ;;
  env)
    write_env "${port:-$(current_port)}" "$bind" "$force"
    ;;
  up)
    require_docker
    write_env "${port:-$(current_port)}" "$bind" "$force"
    compose up --build --detach --wait --wait-timeout 240
    echo
    echo "PISTA 84 is running: http://localhost:$(current_port)"
    echo "Stop it with: bash scripts/local.sh down"
    ;;
  down)
    require_docker
    compose down
    ;;
  reset)
    require_docker
    compose down --volumes
    echo "Local MongoDB data deleted."
    ;;
  logs)
    require_docker
    compose logs --follow --tail 100
    ;;
  status)
    require_docker
    compose ps
    ;;
  check)
    require_docker
    compose exec -T app node scripts/check-online.ts
    compose exec -T app node scripts/check-local.ts
    ;;
  test)
    require_docker
    compose exec -T app node scripts/check-online.ts
    compose exec -T app node scripts/check-local.ts
    compose exec -T app npm run typecheck
    compose exec -T app npm test
    ;;
  *)
    die "Unknown command: $command_name (see: bash scripts/local.sh help)"
    ;;
esac
